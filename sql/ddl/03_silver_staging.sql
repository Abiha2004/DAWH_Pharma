CREATE TABLE IF NOT EXISTS staging.medicine (
    medicine_id                 TEXT    NOT NULL,
    effective_from_date         DATE    NOT NULL,
    internal_sku                TEXT,
    gtin14                      TEXT,
    generic_name                TEXT,
    brand_name                  TEXT,
    disease_category            TEXT,
    icd10_category              TEXT,
    atc_code                    TEXT,
    therapeutic_class           TEXT,
    dosage_form                 TEXT,
    strength                    TEXT,
    route_of_administration     TEXT,
    pack_size                   INTEGER,
    base_uom                    TEXT,
    prescription_class          TEXT,
    controlled_flag             BOOLEAN,
    cold_chain_flag             BOOLEAN,
    storage_min_temp_c          NUMERIC(6,2),
    storage_max_temp_c          NUMERIC(6,2),
    max_humidity_pct            NUMERIC(6,2),
    shelf_life_months           INTEGER,
    min_remaining_shelf_days    INTEGER,
    primary_supplier_id         TEXT,
    primary_plant_id            TEXT,
    mfg_lead_time_days          INTEGER,
    standard_batch_size_packs   INTEGER,
    safety_stock_days           INTEGER,
    reorder_review_cycle_days   INTEGER,
    unit_mfg_cost_usd           NUMERIC(12,4),
    wholesale_price_usd         NUMERIC(12,4),
    rrp_usd                     NUMERIC(12,4),
    product_status              TEXT,
    source_system               TEXT,
    _batch_id                   INTEGER NOT NULL,
    _loaded_at                  TIMESTAMPTZ DEFAULT now(),
