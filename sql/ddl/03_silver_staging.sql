    id              BIGSERIAL PRIMARY KEY,
    batch_id        INTEGER,
    source_domain   TEXT,
    natural_key     TEXT,
    failed_rule     TEXT,
    payload         JSONB,
    rejected_at     TIMESTAMPTZ DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ix_q_batch ON quarantine.rejected_rows (batch_id);
